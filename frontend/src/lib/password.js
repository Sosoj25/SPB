// กติกาตั้งรหัสผ่านที่เดียว ใช้ร่วมกันทั้งหน้าสมัครสมาชิกและหน้าตั้งรหัสผ่านใหม่
// ไม่งั้นหน้าใดหน้าหนึ่งจะกลายเป็นทางลัดให้ตั้งรหัสผ่านที่อ่อนกว่าที่กำหนดไว้
export const PASSWORD_MIN_LENGTH = 8;

export const PASSWORD_HINT =
  "อย่างน้อย 8 ตัวอักษร มีพิมพ์ใหญ่และพิมพ์เล็กอย่างน้อยอย่างละ 1 ตัว";

// คืนข้อความ error ถ้ารหัสผ่านไม่ผ่านเกณฑ์ คืน "" ถ้าผ่าน
// (ปล่อยให้ผู้เรียกจัดการกรณีเว้นว่าง เพราะข้อความต่างกันในแต่ละหน้า)
export function validatePassword(password) {
  if (password.length < PASSWORD_MIN_LENGTH) {
    return `รหัสผ่านต้องมีอย่างน้อย ${PASSWORD_MIN_LENGTH} ตัวอักษร`;
  }

  if (!/[A-Z]/.test(password)) {
    return "รหัสผ่านต้องมีตัวอักษรพิมพ์ใหญ่ (A-Z) อย่างน้อย 1 ตัว";
  }

  if (!/[a-z]/.test(password)) {
    return "รหัสผ่านต้องมีตัวอักษรพิมพ์เล็ก (a-z) อย่างน้อย 1 ตัว";
  }

  return "";
}
