-- ============================================================
-- 5. RLS
-- ============================================================

alter table public.facilities_page_settings enable row level security;
alter table public.club_amenities enable row level security;
alter table public.club_amenity_facts enable row level security;

-- ส่วนหัวหน้าเป็นแค่ข้อความ ไม่มี flag ซ่อน — อ่านได้เสมอ แก้ได้เฉพาะ admin
drop policy if exists "facilities_page_settings_public_read" on public.facilities_page_settings;
create policy "facilities_page_settings_public_read"
on public.facilities_page_settings
for select
to anon, authenticated
using ( true );

drop policy if exists "facilities_page_settings_admin_manage" on public.facilities_page_settings;
create policy "facilities_page_settings_admin_manage"
on public.facilities_page_settings
for update
to authenticated
using ( public.is_admin() )
with check ( public.is_admin() );

drop policy if exists "club_amenities_public_read" on public.club_amenities;
create policy "club_amenities_public_read"
on public.club_amenities
for select
to anon, authenticated
using (
    is_visible = true
    or public.is_admin()
);

drop policy if exists "club_amenities_admin_manage" on public.club_amenities;
create policy "club_amenities_admin_manage"
on public.club_amenities
for all
to authenticated
using ( public.is_admin() )
with check ( public.is_admin() );

-- ตารางลูก facts ไม่มีคอลัมน์ is_visible ของตัวเอง — มองตามการมองเห็นของ
-- amenity แม่เสมอ (ผูก join กับ club_amenities แทนเก็บซ้ำ)
drop policy if exists "club_amenity_facts_public_read" on public.club_amenity_facts;
create policy "club_amenity_facts_public_read"
on public.club_amenity_facts
for select
to anon, authenticated
using (
    exists (
        select 1 from public.club_amenities a
        where a.id = amenity_id
        and (a.is_visible = true or public.is_admin())
    )
);

drop policy if exists "club_amenity_facts_admin_manage" on public.club_amenity_facts;
create policy "club_amenity_facts_admin_manage"
on public.club_amenity_facts
for all
to authenticated
using ( public.is_admin() )
with check ( public.is_admin() );


-- ============================================================
-- 6. Storage bucket สำหรับรูปสิ่งอำนวยความสะดวก
-- ============================================================

insert into storage.buckets (id, name, public)
values ('amenities', 'amenities', true)
on conflict (id) do nothing;

drop policy if exists "Amenity images are publicly accessible" on storage.objects;
create policy "Amenity images are publicly accessible"
on storage.objects for select
using ( bucket_id = 'amenities' );

drop policy if exists "Admins can upload amenity images" on storage.objects;
create policy "Admins can upload amenity images"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'amenities'
  and public.is_admin()
);

drop policy if exists "Admins can update amenity images" on storage.objects;
create policy "Admins can update amenity images"
on storage.objects for update
to authenticated
using (
  bucket_id = 'amenities'
  and public.is_admin()
);

drop policy if exists "Admins can delete amenity images" on storage.objects;
create policy "Admins can delete amenity images"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'amenities'
  and public.is_admin()
);
