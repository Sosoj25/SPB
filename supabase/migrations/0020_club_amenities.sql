-- ============================================================
-- 2. รายการสิ่งอำนวยความสะดวก
-- ============================================================

create table if not exists public.club_amenities (

    id bigint generated by default as identity primary key,

    name varchar(200) not null,

    category varchar(100) not null default '',

    description text not null default '',

    image_url text,

    position integer not null default 0,

    is_visible boolean not null default true,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint club_amenities_unique_name unique (name),

    constraint club_amenities_position_check check (position >= 0)

);

create index if not exists idx_club_amenities_position
on public.club_amenities(position);

drop trigger if exists trg_club_amenities_updated_at
on public.club_amenities;

create trigger trg_club_amenities_updated_at
before update on public.club_amenities
for each row
execute function public.set_updated_at();


-- ============================================================
-- 3. ข้อมูลรายละเอียดแบบ label/value ของแต่ละรายการ (เพิ่ม/ลบได้จาก edit panel)
-- ============================================================

create table if not exists public.club_amenity_facts (

    id bigint generated by default as identity primary key,

    amenity_id bigint not null
        references public.club_amenities(id)
        on delete cascade,

    label varchar(100) not null,

    value varchar(200) not null,

    position integer not null default 0,

    constraint club_amenity_facts_unique_label unique (amenity_id, label)

);

create index if not exists idx_club_amenity_facts_amenity
on public.club_amenity_facts(amenity_id);


