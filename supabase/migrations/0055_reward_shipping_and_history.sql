-- ถ้าไม่รู้ว่าเป็นของขนส่งเจ้าไหน (เลขของ Kerry กับ Flash หน้าตาใกล้กันมาก)

alter table public.reward_redemptions
  add column if not exists shipping_carrier text,
  add column if not exists shipping_note    text,
  add column if not exists delivered_at     timestamptz,
  add column if not exists received_at      timestamptz;

-- 'shipping' ของเดิมกำกวม (ส่งแล้ว? หรือกำลังไปถึง?) — ย้ายไปเป็น 'in_transit'
-- ที่มีความหมายเดียว หน้าเว็บยังแมป 'shipping' ไว้เผื่อแถวที่หลุดรอดมา
update public.reward_redemptions
set fulfillment_status = 'in_transit'
where fulfillment_status = 'shipping';


-- ============================================================
-- 2. ไทม์ไลน์การจัดส่ง
-- ============================================================
-- เก็บทุกครั้งที่สถานะขยับเป็นแถวใหม่ ไม่ใช่ทับค่าเดิม — ลูกค้าต้องเห็นว่า
-- "เตรียมของวันที่ 1 ส่งวันที่ 2 ถึงวันที่ 4" ไม่ใช่เห็นแค่สถานะล่าสุดลอย ๆ
-- และเวลามีปัญหา (ของตีกลับ ส่งซ้ำ) จะมีหลักฐานว่าเกิดอะไรขึ้นตามลำดับ

create table if not exists public.reward_shipment_events (
  id              bigint generated by default as identity primary key,
  redemption_id   uuid not null references public.reward_redemptions(id) on delete cascade,
  status          public.reward_fulfillment_status not null,
  note            text,
  tracking_number text,
  carrier         text,
  created_by      uuid references public.profiles(id) on delete set null,
  created_at      timestamptz not null default now()
);

create index if not exists idx_shipment_events_redemption
on public.reward_shipment_events(redemption_id, created_at);

alter table public.reward_shipment_events enable row level security;

-- อ่านได้เฉพาะเจ้าของคูปองกับแอดมิน และไม่มี policy insert/update/delete เลย
-- โดยตั้งใจ — ทุกแถวเกิดจาก RPC security definer ข้างล่างเท่านั้น ลูกค้าจึง
-- ปลอมไทม์ไลน์ว่า "ส่งแล้ว" เองไม่ได้
drop policy if exists "shipment_events_read" on public.reward_shipment_events;
create policy "shipment_events_read"
on public.reward_shipment_events
for select
to authenticated
using (
  public.is_admin()
  or exists (
    select 1 from public.reward_redemptions rr
    where rr.id = redemption_id
      and rr.user_id = (select auth.uid())
  )
);

revoke all on public.reward_shipment_events from anon, authenticated;
grant select on public.reward_shipment_events to authenticated;


-- ============================================================
-- 3. ลำดับขั้นของสถานะจัดส่ง
-- ============================================================
-- ใช้ทั้งตอนตรวจว่าเดินหน้าถูกทางไหม และตอนเรียงไทม์ไลน์ — เขียนที่เดียวเพื่อ
-- ไม่ให้ฝั่ง SQL กับฝั่งหน้าเว็บนิยามลำดับไม่ตรงกัน
--
-- pickup แยกเส้นทาง (นัดรับที่สนาม ไม่มีขนส่งมาเกี่ยว) จึงให้ step เท่ากับ
-- "จัดส่งสำเร็จ" คือรอแค่ลูกค้ามารับแล้วกดยืนยัน

create or replace function public.reward_fulfillment_step(
  p_status public.reward_fulfillment_status
)
returns integer
language sql
immutable
as $$
  select case p_status
    when 'pending'    then 0
    when 'preparing'  then 1
    when 'shipped'    then 2
    when 'shipping'   then 3
    when 'in_transit' then 3
    when 'pickup'     then 4
    when 'delivered'  then 4
    when 'received'   then 5
    else 0
  end;
$$;

grant execute on function public.reward_fulfillment_step(public.reward_fulfillment_status)
  to authenticated, anon;


-- ============================================================
-- 4. อัปเดตสถานะจัดส่ง (แอดมิน)
-- ============================================================
-- signature เปลี่ยน (เพิ่ม carrier/note) จึงต้อง drop ตัวเก่าทิ้งก่อน ไม่งั้น
-- จะมีสองตัวชื่อเดียวกันแล้ว PostgREST เลือกไม่ถูก
--
-- 'received' ไม่ให้แอดมินตั้งเอง — "ลูกค้ายืนยันได้รับแล้ว" ต้องมาจากลูกค้า
-- เท่านั้น ไม่งั้นสถานะนั้นก็ไม่ได้แปลว่าอะไรเลย
--
-- ปิดคูปองเป็น completed ตอน 'delivered' (ไม่ใช่ตอน 'shipped' แบบเดิม) เพราะ
-- ของที่เพิ่งออกจากคลังยังไม่ถึงมือใคร ถ้านับว่า "ใช้แล้ว" ตั้งแต่ตอนนั้น
-- ตัวเลข "แลกแล้วยังไม่ได้ใช้" ของแอดมินจะต่ำกว่าความจริงตลอด

drop function if exists public.admin_update_redemption_fulfillment(
  uuid, public.reward_fulfillment_status, text
);

create or replace function public.admin_update_redemption_fulfillment(
  p_id       uuid,
  p_status   public.reward_fulfillment_status,
  p_tracking text default null,
  p_carrier  text default null,
  p_note     text default null
)
returns public.reward_redemptions
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_row    public.reward_redemptions;
  v_reward public.rewards;
  v_label  text;
begin
  if not public.is_admin() then
    raise exception 'ต้องเป็นผู้ดูแลระบบเท่านั้น';
  end if;

  if p_status = 'received' then
    raise exception 'สถานะ "ลูกค้ายืนยันได้รับแล้ว" ต้องให้ลูกค้าเป็นคนกดยืนยันเอง';
  end if;

  select * into v_row
  from public.reward_redemptions
  where id = p_id
  for update;

  if not found then
    raise exception 'ไม่พบคำขอแลกรางวัลนี้';
  end if;

  if v_row.status = 'cancelled' then
    raise exception 'คำขอนี้ถูกยกเลิกไปแล้ว';
  end if;

  if v_row.fulfillment_status is null then
    raise exception 'ของรางวัลนี้ไม่ต้องจัดส่ง จึงอัปเดตสถานะจัดส่งไม่ได้';
  end if;

  if v_row.fulfillment_status = 'received' then
    raise exception 'ลูกค้ายืนยันรับของแล้ว ไม่สามารถเปลี่ยนสถานะย้อนกลับได้';
  end if;

  select * into v_reward from public.rewards where id = v_row.reward_id;

  update public.reward_redemptions
  set fulfillment_status = p_status,
      tracking_number    = coalesce(nullif(btrim(coalesce(p_tracking, '')), ''), tracking_number),
      shipping_carrier   = coalesce(nullif(btrim(coalesce(p_carrier, '')), ''), shipping_carrier),
      shipping_note      = coalesce(nullif(btrim(coalesce(p_note, '')), ''), shipping_note),
      shipped_at         = case when p_status = 'shipped'   then coalesce(shipped_at, now())   else shipped_at end,
      delivered_at       = case when p_status = 'delivered' then coalesce(delivered_at, now()) else delivered_at end,
      status             = case when p_status = 'delivered' then 'completed'::public.redemption_status else status end,
      used_at            = case when p_status = 'delivered' then coalesce(used_at, now()) else used_at end
  where id = p_id
  returning * into v_row;

  insert into public.reward_shipment_events
    (redemption_id, status, note, tracking_number, carrier, created_by)
  values (
    p_id,
    p_status,
    nullif(btrim(coalesce(p_note, '')), ''),
    v_row.tracking_number,
    v_row.shipping_carrier,
    (select auth.uid())
  );

  v_label := case p_status
    when 'preparing'  then 'กำลังเตรียมสินค้า'
    when 'shipped'    then 'จัดส่งแล้ว'
    when 'in_transit' then 'อยู่ระหว่างขนส่ง'
    when 'delivered'  then 'จัดส่งสำเร็จ'
    when 'pickup'     then 'พร้อมให้รับที่สนาม'
    else 'รอดำเนินการ'
  end;

  -- ไม่แจ้งเตือนตอนถอยกลับไป 'pending' — เป็นการแก้ข้อมูลฝั่งหลังบ้าน ไม่ใช่
  -- ความคืบหน้าที่ลูกค้าต้องรู้
  if p_status <> 'pending' then
    insert into public.notifications
      (user_id, type, title, message, reference_type, reference_id)
    values (
      v_row.user_id,
      'reward_shipping',
      format('ของรางวัล: %s', v_label),
      format(
        '"%s" %s%s%s',
        v_reward.name,
        v_label,
        coalesce(' · เลขพัสดุ ' || v_row.tracking_number, ''),
        case when p_status = 'delivered'
             then ' — กรุณากดยืนยันเมื่อได้รับของแล้วที่หน้าประวัติการแลกรางวัล'
             else '' end
      ),
      'redemption',
      v_row.id::text
    );
  end if;

  return v_row;
end;
$fn$;

revoke all on function public.admin_update_redemption_fulfillment(
  uuid, public.reward_fulfillment_status, text, text, text
) from public, anon;
grant execute on function public.admin_update_redemption_fulfillment(
  uuid, public.reward_fulfillment_status, text, text, text
) to authenticated, service_role;


-- ============================================================
-- 5. ลูกค้ายืนยันว่าได้รับของรางวัลแล้ว
-- ============================================================
-- ใช้ได้ตั้งแต่ของออกจากคลังไปแล้ว (shipped ขึ้นไป) รวมถึงของที่นัดรับที่สนาม
-- — ก่อนหน้านั้นยังไม่มีอะไรให้ยืนยัน
--
-- ปิดคูปองเป็น completed ด้วยเสมอ ต่อให้แอดมินยังไม่ได้กด 'delivered' เพราะ
-- ของถึงมือลูกค้าจริงแล้วคือจุดจบของรายการนี้ ไม่ว่าสถานะฝั่งหลังบ้านจะตามทัน
-- หรือไม่

create or replace function public.confirm_redemption_received(
  p_id   uuid,
  p_note text default null
)
returns public.reward_redemptions
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_me  uuid := (select auth.uid());
  v_row public.reward_redemptions;
begin
  if v_me is null then
    raise exception 'ต้องเข้าสู่ระบบก่อน';
  end if;

  select * into v_row
  from public.reward_redemptions
  where id = p_id
  for update;

  if not found or v_row.user_id <> v_me then
    raise exception 'ไม่พบรายการแลกรางวัลนี้';
  end if;

  if v_row.status = 'cancelled' then
    raise exception 'รายการนี้ถูกยกเลิกไปแล้ว';
  end if;

  if v_row.fulfillment_status is null then
    raise exception 'ของรางวัลนี้ไม่มีการจัดส่ง จึงไม่ต้องยืนยันการรับของ';
  end if;

  if v_row.fulfillment_status = 'received' then
    return v_row;
  end if;

  if public.reward_fulfillment_step(v_row.fulfillment_status) < 2 then
    raise exception 'ของรางวัลยังไม่ถูกจัดส่ง ยังยืนยันการรับของไม่ได้';
  end if;

  update public.reward_redemptions
  set fulfillment_status = 'received',
      received_at        = coalesce(received_at, now()),
      delivered_at       = coalesce(delivered_at, now()),
      status             = 'completed',
      used_at            = coalesce(used_at, now()),
      used_note          = coalesce(used_note, nullif(btrim(coalesce(p_note, '')), ''),
                                    'ลูกค้ายืนยันว่าได้รับของรางวัลแล้ว')
  where id = p_id
  returning * into v_row;

  insert into public.reward_shipment_events
    (redemption_id, status, note, tracking_number, carrier, created_by)
  values (
    p_id,
    'received',
    coalesce(nullif(btrim(coalesce(p_note, '')), ''), 'ลูกค้ายืนยันว่าได้รับของรางวัลแล้ว'),
    v_row.tracking_number,
    v_row.shipping_carrier,
    v_me
  );

  return v_row;
end;
$fn$;

revoke all on function public.confirm_redemption_received(uuid, text) from public, anon;
grant execute on function public.confirm_redemption_received(uuid, text) to authenticated;


-- ============================================================
-- 6. สรุปคิวจัดส่ง (แอดมิน) — ตามสถานะชุดใหม่
-- ============================================================
drop function if exists public.admin_reward_fulfillment_stats();

create function public.admin_reward_fulfillment_stats()
returns table (
  pending_count   integer,
  preparing_count integer,
  shipped_count   integer,
  transit_count   integer,
  delivered_count integer,
  received_count  integer,
  pickup_count    integer,
  shipped_month   integer
)
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_month timestamp := date_trunc('month', now() at time zone 'Asia/Bangkok');
begin
  if not public.is_admin() then
    raise exception 'ต้องเป็นผู้ดูแลระบบเท่านั้น';
  end if;

  return query
  select
    count(*) filter (where rr.fulfillment_status = 'pending')::integer,
    count(*) filter (where rr.fulfillment_status = 'preparing')::integer,
    count(*) filter (where rr.fulfillment_status = 'shipped')::integer,
    count(*) filter (where rr.fulfillment_status in ('in_transit', 'shipping'))::integer,
    count(*) filter (where rr.fulfillment_status = 'delivered')::integer,
    count(*) filter (where rr.fulfillment_status = 'received')::integer,
    count(*) filter (where rr.fulfillment_status = 'pickup')::integer,
    count(*) filter (
      where rr.shipped_at is not null
        and date_trunc('month', rr.shipped_at at time zone 'Asia/Bangkok') = v_month
    )::integer
  from public.reward_redemptions rr
  where rr.fulfillment_status is not null
    and rr.status <> 'cancelled';
end;
$fn$;

revoke all on function public.admin_reward_fulfillment_stats() from public, anon;
grant execute on function public.admin_reward_fulfillment_stats() to authenticated, service_role;


