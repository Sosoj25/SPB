-- 9. ตัวเลขสรุปของหน้าประวัติการแลก (แอดมิน)
-- ============================================================
-- ตอบสามคำถามที่โจทย์ถามตรง ๆ: แลกไปทั้งหมดกี่ใบ ใช้ไปแล้วกี่ใบ และแลกแล้ว
-- ยังไม่ได้ใช้กี่ใบ — บวกยอดแต้มที่ถูกใช้ไปกับจำนวนคนที่แลก ซึ่งเป็นสองตัวที่
-- ใช้ประเมินว่าโปรแกรมแต้มคุ้มไหม

create or replace function public.admin_redemption_stats()
returns table (
  total_count      integer,
  used_count       integer,
  unused_count     integer,
  expired_count    integer,
  cancelled_count  integer,
  shipping_count   integer,
  awaiting_receipt integer,
  points_spent     integer,
  member_count     integer
)
language plpgsql
security definer
set search_path = public
as $fn$
begin
  if not public.is_admin() then
    raise exception 'ต้องเป็นผู้ดูแลระบบเท่านั้น';
  end if;

  return query
  select
    count(*)::integer,
    count(*) filter (where rr.status = 'completed')::integer,
    count(*) filter (
      where rr.status = 'pending'
        and (rr.expires_at is null or rr.expires_at >= now())
    )::integer,
    count(*) filter (
      where rr.status = 'pending'
        and rr.expires_at is not null
        and rr.expires_at < now()
    )::integer,
    count(*) filter (where rr.status = 'cancelled')::integer,
    count(*) filter (
      where rr.status <> 'cancelled'
        and rr.fulfillment_status is not null
        and rr.fulfillment_status <> 'received'
    )::integer,
    count(*) filter (
      where rr.status <> 'cancelled'
        and rr.fulfillment_status in ('delivered', 'pickup')
    )::integer,
    coalesce(sum(rr.points_used) filter (where rr.status <> 'cancelled'), 0)::integer,
    count(distinct rr.user_id)::integer
  from public.reward_redemptions rr;
end;
$fn$;

revoke all on function public.admin_redemption_stats() from public, anon;
grant execute on function public.admin_redemption_stats() to authenticated, service_role;


