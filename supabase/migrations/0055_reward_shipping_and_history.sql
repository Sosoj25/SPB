--   3) รางวัล "สิทธิ์จองล่วงหน้า 30 วัน" ที่ seed ไว้เป็น benefit_type='none'
--      คือแลกแล้วไม่มีผลกับระบบเลย ซ้ำร้ายกว่านั้นคือทุกคนจองล่วงหน้าได้ 62 วัน
--      อยู่แล้ว สิทธิ์ที่ขาย 3,000 แต้มจึงให้น้อยกว่าที่ทุกคนมีฟรี


