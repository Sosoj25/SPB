-- 10. สิทธิ์จองล่วงหน้า — ทำให้รางวัลใบนี้มีผลจริง
-- ============================================================
-- ก่อนหน้านี้ระบบไม่เคยจำกัดวันจองล่วงหน้าเลยสักชั้น: ตาราง bookings มีแค่
-- trigger กันวันย้อนหลัง (0005) ส่วนเพดาน 62 วันที่ผู้ใช้เห็นเป็นแค่ max ของ
-- ช่อง input type=date กับช่วงที่ facility_day_availability ยอมตอบ —
-- ยิง create_booking ตรง ๆ ด้วยสล็อตของปีหน้าก็ผ่าน
--
-- ตั้งเพดานจริงที่ 30 วันสำหรับทุกคน (แอดมินแก้ได้) แล้วให้รางวัลใบนี้ต่อ
-- ให้อีกตามจำนวนวันใน benefit_value — สิทธิ์ที่ขาย 3,000 แต้มจึงให้อะไรที่
-- คนอื่นไม่มีจริง ๆ

alter table public.reward_settings
  add column if not exists advance_booking_days integer not null default 30;

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'reward_settings_advance_days_check'
  ) then
    alter table public.reward_settings
      add constraint reward_settings_advance_days_check
      check (advance_booking_days between 1 and 365);
  end if;
end;
$$;

-- ผูกสิทธิประโยชน์ให้รางวัลที่ seed ไว้ใน 0047 — ครั้งเดียวตอนอัปเกรด
-- จากนั้นแอดมินแก้เองได้จากหน้าจัดการรางวัล
update public.rewards
set benefit_type  = 'advance_booking',
    benefit_value = 30,
    description   = 'จองสนามล่วงหน้าได้ไกลกว่าปกติอีก 30 วัน มีผลทันทีที่แลก',
    terms         = 'สิทธิ์มีผล 30 วันนับจากวันที่แลก ใช้ได้กับทุกสนามในเครือ ไม่สามารถโอนสิทธิ์ให้ผู้อื่นได้'
where name = 'สิทธิ์จองล่วงหน้า 30 วัน'
  and benefit_type = 'none';

-- สิทธิ์แบบนี้ไม่ใช่คูปองที่ต้องเอาไปยื่นตอนจอง — มันมีผลกับบัญชีทันทีที่แลก
-- จึงปิดใบเป็น completed ตั้งแต่วินาทีแรก ไม่งั้นจะค้างเป็น "ยังไม่ได้ใช้" อยู่
-- 30 วันทั้งที่ใช้อยู่ตลอดเวลา และจะไปโผล่ใน usable_coupons ให้กดใช้ลดราคา
-- ตอนจ่ายเงินทั้งที่ลดอะไรไม่ได้
--
-- ทำเป็น trigger แทนการแก้ redeem_reward() เพราะฟังก์ชันนั้นยาวและถูกเขียนทับ
-- มาแล้วสองรอบ (0047 -> 0049) การแตะซ้ำมีโอกาสทำของเดิมหายมากกว่าที่ควร
create or replace function public.activate_privilege_redemption()
returns trigger
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_benefit public.reward_benefit_type;
begin
  select benefit_type into v_benefit
  from public.rewards where id = new.reward_id;

  if v_benefit = 'advance_booking' then
    update public.reward_redemptions
    set status    = 'completed',
        used_at   = coalesce(used_at, now()),
        used_note = coalesce(
          used_note,
          format('สิทธิ์จองล่วงหน้ามีผลทันที ถึงวันที่ %s',
                 to_char(new.expires_at at time zone 'Asia/Bangkok', 'DD/MM/YYYY'))
        )
    where id = new.id;
  end if;

  return null;
end;
$fn$;

drop trigger if exists activate_privilege_redemption on public.reward_redemptions;
create trigger activate_privilege_redemption
after insert on public.reward_redemptions
for each row execute function public.activate_privilege_redemption();


-- คูปองที่เอาไปลดค่าสนามได้ — ต้องไม่รวมสิทธิ์จองล่วงหน้า (status = completed
-- กรองออกให้อยู่แล้ว แต่เขียนไว้ตรง ๆ ด้วย เผื่อวันหนึ่งเงื่อนไขสถานะเปลี่ยน)
create or replace view public.usable_coupons
with (security_invoker = on) as
select
  rr.id,
  rr.user_id,
  rr.redemption_code,
  rr.expires_at,
  rr.created_at,
  r.name     as reward_name,
  r.category as reward_category,
  r.benefit_type,
  r.benefit_value
from public.reward_redemptions rr
join public.rewards r on r.id = rr.reward_id
where rr.status = 'pending'
  and r.benefit_type not in ('none', 'advance_booking')
  and (rr.expires_at is null or rr.expires_at > now())
  and not exists (
    select 1 from public.bookings b
    where b.redemption_id = rr.id
      and b.status in ('pending', 'confirmed', 'completed')
  );

revoke all on public.usable_coupons from anon, authenticated;
grant select on public.usable_coupons to authenticated;


-- ============================================================
-- 11. จองล่วงหน้าได้กี่วัน
-- ============================================================
-- _booking_window_days เป็นตัวที่ create_booking ใช้ตัดสินจริง (ไม่ grant ให้
-- ใครเรียกตรง) ส่วน my_booking_window() เป็นตัวที่หน้าเว็บถามเพื่อเซ็ต max ของ
-- ช่องเลือกวันที่ให้ตรงกัน — สองตัวอ่านสูตรเดียวกัน หน้าเว็บจึงไม่มีทางโชว์
-- วันที่ที่ backend จะปฏิเสธ
--
-- นับสิทธิ์ที่ยังไม่หมดอายุด้วย max() ไม่ใช่ sum() — แลกสิทธิ์เดิมซ้ำสองใบ
-- ไม่ได้แปลว่าจองไกลขึ้นเป็นสองเท่า

create or replace function public._booking_window_days(p_user uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (select advance_booking_days from public.reward_settings where id = 1),
    30
  ) + coalesce(
    (select max(r.benefit_value)::int
       from public.reward_redemptions rr
       join public.rewards r on r.id = rr.reward_id
      where rr.user_id = p_user
        and r.benefit_type = 'advance_booking'
        and rr.status <> 'cancelled'
        and (rr.expires_at is null or rr.expires_at > now())),
    0
  );
$$;

revoke all on function public._booking_window_days(uuid) from public, anon, authenticated;


create or replace function public.my_booking_window()
returns table (
  base_days   integer,
  bonus_days  integer,
  total_days  integer,
  last_date   date,
  bonus_until timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    v.base,
    v.bonus,
    v.base + v.bonus,
    ((now() at time zone 'Asia/Bangkok')::date + (v.base + v.bonus)),
    v.until
  from (
    select
      coalesce((select advance_booking_days from public.reward_settings where id = 1), 30) as base,
      coalesce((select max(r.benefit_value)::int
                  from public.reward_redemptions rr
                  join public.rewards r on r.id = rr.reward_id
                 where rr.user_id = (select auth.uid())
                   and r.benefit_type = 'advance_booking'
                   and rr.status <> 'cancelled'
                   and (rr.expires_at is null or rr.expires_at > now())), 0) as bonus,
      (select max(rr.expires_at)
         from public.reward_redemptions rr
         join public.rewards r on r.id = rr.reward_id
        where rr.user_id = (select auth.uid())
          and r.benefit_type = 'advance_booking'
          and rr.status <> 'cancelled'
          and (rr.expires_at is null or rr.expires_at > now())) as until
  ) v;
$$;

revoke all on function public.my_booking_window() from public, anon;
grant execute on function public.my_booking_window() to authenticated;
