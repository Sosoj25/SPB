-- ============================================================
-- 8. ประวัติการแลกรางวัลทั้งหมด (แอดมิน)
-- ============================================================
-- ต่างจาก admin_reward_requests ตรงที่ "ไม่กรอง" — รวมคูปองส่วนลดที่ไม่ต้อง
-- ส่งของด้วย เพราะคำถามที่หน้านี้ต้องตอบคือ "ใครแลกอะไรไปบ้าง" ไม่ใช่
-- "เหลืออะไรต้องส่ง"
--
-- usage_state คำนวณด้วยสูตรเดียวกับ redemptionState() ฝั่งหน้าเว็บ (0047) —
-- "หมดอายุ" ไม่ใช่ค่าที่เก็บไว้ในตาราง จึงต้องคิดสด ๆ ทุกครั้งที่อ่าน
--
-- security definer view (ไม่ใส่ security_invoker) เหมือน admin_reward_requests
-- เพราะต้องอ่านชื่อ/เบอร์ของลูกค้าคนอื่นซึ่ง profiles_select_own ปิดไว้ —
-- is_admin() ใน where เป็นตัวกั้นเอง

create or replace view public.admin_redemption_history as
select
  rr.id,
  rr.user_id,
  rr.reward_id,
  rr.redemption_code,
  rr.points_used,
  rr.status,
  rr.fulfillment_status,
  rr.option_label,
  rr.recipient_name,
  rr.shipping_phone,
  rr.shipping_address,
  rr.tracking_number,
  rr.shipping_carrier,
  rr.shipped_at,
  rr.delivered_at,
  rr.received_at,
  rr.used_at,
  rr.used_note,
  rr.cancel_reason,
  rr.expires_at,
  rr.created_at,
  case
    when rr.status = 'cancelled' then 'cancelled'
    when rr.status = 'completed' then 'used'
    when rr.expires_at is not null and rr.expires_at < now() then 'expired'
    else 'unused'
  end as usage_state,
  r.name      as reward_name,
  r.category  as reward_category,
  r.image_url as reward_image,
  r.benefit_type,
  r.requires_shipping,
  p.username,
  p.full_name,
  p.avatar_url,
  p.phone
from public.reward_redemptions rr
join public.rewards  r on r.id = rr.reward_id
join public.profiles p on p.id = rr.user_id
where public.is_admin();

grant select on public.admin_redemption_history to authenticated;


