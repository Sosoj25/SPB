-- ============================================================
-- ให้ view ของหน้าแอดมินมี RLS เป็นด่านรองใต้ where is_admin()
-- ============================================================
-- admin_redemption_history กับ admin_reward_requests เป็น view แบบ security
-- definer (ค่าเริ่มต้น) ซึ่งแปลว่ามันอ่านตารางต้นทางด้วยสิทธิ์ของ "เจ้าของ view"
-- ไม่ใช่ของคนเรียก — RLS ของ reward_redemptions / profiles จึงถูกข้ามไปทั้งหมด
-- เหลือ `where is_admin()` ท้าย view เป็นด่านเดียวที่กันข้อมูลลูกค้าทุกคน
-- (ชื่อจริง เบอร์โทร ที่อยู่จัดส่ง) ไว้
--
-- ด่านเดียวแปลว่าถ้าวันไหนมีคนแก้ view แล้วเผลอตัดบรรทัดนั้นทิ้ง ข้อมูลหลุด
-- ทันทีโดยไม่มีอะไรกั้นต่อ — เป็นสิ่งที่ Supabase advisor รายงานเป็นระดับ ERROR
--
-- เปลี่ยนเป็น security_invoker ได้โดยไม่กระทบการใช้งานจริง เพราะทดสอบแล้วว่า
-- บัญชีแอดมินผ่าน RLS ของตารางต้นทางครบทั้งสามตัวอยู่แล้ว:
--
--   reward_redemptions : redemptions_select_own -> user_id = auth.uid() OR is_admin()
--   profiles           : profiles_select_own    -> id = auth.uid()      OR is_admin()
--   rewards            : อ่านได้ทั่วไป
--
-- ผลคือด่านกลายเป็นสองชั้น: where is_admin() ของ view + RLS ของทุกตารางข้างใต้
--
-- ------------------------------------------------------------
-- ทำไม public_profiles / community_profile_stats ไม่แก้ตาม
-- ------------------------------------------------------------
-- สอง view นั้น advisor รายงานเป็น ERROR เหมือนกัน แต่แก้แบบนี้ไม่ได้ —
-- มันคือ "หน้ากาก" ที่ตั้งใจเปิดเฉพาะคอลัมน์ปลอดภัยของ profiles ให้ผู้ใช้คนอื่น
-- เห็นกัน ซึ่ง RLS ของ profiles (เห็นได้แค่แถวตัวเอง) ไม่มีทางยอม ถ้าเปลี่ยนเป็น
-- invoker ผู้ใช้จะเห็นโปรไฟล์ของตัวเองคนเดียว ฟีเจอร์ชุมชนพังทั้งหมด
-- ความเสี่ยงจริงของสองตัวนั้นคือการ grant ให้ anon ซึ่งปิดไปแล้วที่ 0099
-- ============================================================

alter view public.admin_redemption_history set (security_invoker = on);
alter view public.admin_reward_requests   set (security_invoker = on);
