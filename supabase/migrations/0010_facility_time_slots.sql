-- venue แล้ว generate ช่องละ 1 ชม. ให้อัตโนมัติ
--
-- แต่ระบบจริงคือ "แอดมินเป็นคนลงว่าวันนี้เปิดให้จองช่วงไหนบ้าง" ซึ่งต่างกัน
-- สองเรื่อง:
--   1. แต่ละวันเปิดไม่เหมือนกันได้ (วันหยุด, วันปิดซ่อม, จัดแข่งครึ่งวัน)
--   2. ช่วงเวลาไม่จำเป็นต้องยาวเท่ากันหรือต่อกันสนิท (เว้นพักกลางวันได้)
-- ทั้งสองเรื่องนี้ generate จากเวลาเปิด-ปิดไม่ได้ ต้องมีตารางเก็บจริง
--
-- ผลพลอยได้ด้านความปลอดภัย: เมื่อ client ส่งได้แค่ "id ของช่วงเวลา"
-- เวลาเริ่ม-จบก็ไม่มีทางถูกกำหนดจากฝั่งผู้ใช้อีกเลย (ดูต่อใน 0011)


-- ============================================================
-- 1. ตารางช่วงเวลาที่เปิดให้จอง
-- ============================================================

create table if not exists public.facility_time_slots (

    id bigint generated by default as identity primary key,

    facility_id bigint not null
        references public.facilities(id)
        on delete cascade,

    slot_date date not null,

    start_time time not null,

    end_time time not null,

    -- ปิดช่วงเวลาชั่วคราวโดยไม่ลบทิ้ง (การจองเดิมที่ผูกอยู่จะได้ไม่หายไปด้วย)
    is_active boolean not null default true,

    created_at timestamptz not null default now(),

    updated_at timestamptz not null default now(),

    constraint facility_time_slots_time_check
        check (end_time > start_time),

    constraint facility_time_slots_unique
        unique (facility_id, slot_date, start_time)

);


-- ============================================================
-- 2. กันแอดมินลงช่วงเวลาทับกันเอง
-- ============================================================
-- unique (facility_id, slot_date, start_time) กันได้แค่ "เริ่มเวลาเดียวกัน"
-- แต่ 09:00-11:00 กับ 10:00-12:00 เริ่มคนละเวลา ผ่าน unique ไปได้สบาย
-- แล้วผู้ใช้สองคนจะจองสองช่วงนี้พร้อมกันไม่ได้ (ชนกันที่ bookings) —
-- กลายเป็นช่วงเวลาที่โชว์ว่าว่างแต่จองไม่ได้จริง
--
-- ใช้วิธีเดียวกับ bookings_no_overlap ใน 0000: generated tsrange + gist

alter table public.facility_time_slots
add column if not exists slot_span tsrange
generated always as (
    tsrange(
        (slot_date + start_time)::timestamp,
        (slot_date + end_time)::timestamp,
        '[)'
    )
) stored;


alter table public.facility_time_slots
drop constraint if exists facility_time_slots_no_overlap;


alter table public.facility_time_slots
add constraint facility_time_slots_no_overlap
exclude using gist (
    facility_id with =,
    slot_span with &&
);


create index if not exists idx_facility_time_slots_lookup
on public.facility_time_slots (facility_id, slot_date);


drop trigger if exists trg_facility_time_slots_updated_at
on public.facility_time_slots;

create trigger trg_facility_time_slots_updated_at
before update on public.facility_time_slots
for each row
execute function public.set_updated_at();


-- ============================================================
