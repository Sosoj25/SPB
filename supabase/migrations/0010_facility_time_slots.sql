-- ============================================================
-- 4. ตัวช่วยสร้างช่วงเวลาทีละหลายวัน
-- ============================================================
-- ตารางเป็นรายวันตามที่ต้องการ แต่การคีย์มือ 15 สนาม x 60 วัน = ~900 แถว
-- ไม่ใช่งานที่คนควรทำ ฟังก์ชันนี้คือปุ่ม "เปิดจองล่วงหน้า 1 เดือน" ของหน้า
-- Admin — สร้างแบบสม่ำเสมอให้ก่อน แล้วแอดมินค่อยเข้าไปลบ/แก้เป็นวัน ๆ
--
-- ตั้งใจให้เป็น SECURITY INVOKER (ค่าเริ่มต้น) ไม่ใช่ DEFINER:
-- สิทธิ์การเขียนจึงถูกตัดสินโดย facility_time_slots_admin_manage ตามปกติ
-- ไม่ต้องเช็ค is_admin() ซ้ำในตัวฟังก์ชัน และไม่มีทางลืมเช็ค
--
-- คืนจำนวนแถวที่สร้างจริง — ช่วงที่ทับของเดิมจะถูกข้าม ไม่ใช่ error
-- ทำให้กดซ้ำเพื่อ "ต่ออายุอีกเดือน" ได้โดยไม่ต้องกลัวพัง

create or replace function public.generate_facility_slots(
  p_facility_id   bigint,
  p_from          date,
  p_to            date,
  p_start_time    time,
  p_end_time      time,
  p_slot_minutes  integer default 60
)
returns integer
language plpgsql
set search_path = public
as $fn$
declare
  v_inserted integer;
begin
  if p_slot_minutes <= 0 then
    raise exception 'ความยาวช่วงเวลาต้องมากกว่า 0 นาที';
  end if;

  if p_end_time <= p_start_time then
    raise exception 'เวลาสิ้นสุดต้องอยู่หลังเวลาเริ่ม';
  end if;

  if p_to < p_from then
    raise exception 'วันสิ้นสุดต้องไม่อยู่ก่อนวันเริ่ม';
  end if;

  if p_to - p_from > 365 then
    raise exception 'สร้างล่วงหน้าได้ไม่เกิน 365 วันต่อครั้ง';
  end if;

  with candidate as (
    select
      d::date                                              as slot_date,
      g::time                                              as start_time,
      (g + make_interval(mins => p_slot_minutes))::time    as end_time
    from generate_series(p_from, p_to, interval '1 day') as d
    cross join lateral generate_series(
      d::date + p_start_time,
      -- ตัดเศษท้ายทิ้ง: เปิด 08:00-23:00 ช่วงละ 2 ชม. ได้ถึง 20:00-22:00
      -- ไม่สร้าง 22:00-24:00 ที่ล้นเวลาปิด
      d::date + p_end_time - make_interval(mins => p_slot_minutes),
      make_interval(mins => p_slot_minutes)
    ) as g
  )
  insert into public.facility_time_slots (facility_id, slot_date, start_time, end_time)
  select p_facility_id, c.slot_date, c.start_time, c.end_time
  from candidate c
  where not exists (
    -- ข้ามช่วงที่ทับของเดิม ไม่ใช่ปล่อยให้ exclusion constraint โยน error
    -- ทั้งชุด เพราะแอดมินอาจเคยลงช่วงพิเศษของบางวันไว้แล้ว
    select 1
    from public.facility_time_slots x
    where x.facility_id = p_facility_id
      and x.slot_date   = c.slot_date
      and x.start_time  < c.end_time
      and x.end_time    > c.start_time
  );

  get diagnostics v_inserted = row_count;

  return v_inserted;
end;
$fn$;


revoke all on function
  public.generate_facility_slots(bigint, date, date, time, time, integer)
from public, anon;

grant execute on function
  public.generate_facility_slots(bigint, date, date, time, time, integer)
to authenticated;


-- ============================================================
-- 5. เปิดจองล่วงหน้า 60 วันให้สนามที่ seed ไว้ใน 0008
-- ============================================================
-- ความยาวช่วงแยกตามชนิดกีฬา: คอร์ตแบด/เทนนิสเช่ากันเป็นชั่วโมง
-- ส่วนสนามทีมมักเล่นกันรอบละ 2 ชม.
--
-- ข้อควรรู้: ช่วงเวลาหมดอายุไปตามวัน พอเลย 60 วันแล้วจะไม่มีอะไรให้จอง
-- จนกว่าแอดมินจะกดสร้างเพิ่ม — เป็นธรรมชาติของตารางรายวัน ไม่ใช่บั๊ก

do $$
declare
  r record;
begin
  for r in
    select
      f.id,
      v.opening_time,
      v.closing_time,
      case when s.name in ('แบดมินตัน', 'เทนนิส') then 60 else 120 end as slot_minutes
    from public.facilities f
    join public.venues v on v.id = f.venue_id
    join public.sports s on s.id = f.sport_id
    where f.status = 'available'
      and v.status = 'active'
  loop
    perform public.generate_facility_slots(
      r.id,
      current_date,
      current_date + 60,
      r.opening_time,
      r.closing_time,
      r.slot_minutes
    );
  end loop;
end;
$$;
